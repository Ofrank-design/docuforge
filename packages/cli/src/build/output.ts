import fs from "node:fs/promises";
import path from "node:path";
import { DocuForgeError, ExitCode } from "../util/errors.js";
import { resolveInside } from "../util/paths.js";
import { writeFileAtomic, pathExists } from "../util/fs.js";

/** Written into every output directory DocuForge creates; `--clean` only deletes directories that have it. */
export const OUTPUT_MARKER = ".docuforge-build";

export interface PrepareResult {
  /** True when the directory already held files that DocuForge did not create. */
  foreignContent: boolean;
}

/**
 * Create (or clean) the output directory safely.
 * `--clean` refuses to delete anything that is not empty and not marked as
 * DocuForge output, so a mistyped `--out` can never wipe a real directory.
 */
export async function prepareOutputDir(outDir: string, clean: boolean): Promise<PrepareResult> {
  if (path.parse(outDir).root === outDir) {
    throw new DocuForgeError("Refusing to use the filesystem root as the output directory.", ExitCode.Usage);
  }

  let foreignContent = false;
  if (await pathExists(outDir)) {
    const st = await fs.lstat(outDir);
    if (!st.isDirectory()) {
      throw new DocuForgeError(`Output path exists and is not a directory: ${outDir}`, ExitCode.Usage);
    }
    const entries = await fs.readdir(outDir);
    const marked = entries.includes(OUTPUT_MARKER);
    if (clean) {
      if (entries.length > 0 && !marked) {
        throw new DocuForgeError(
          `Refusing to clean ${outDir}: it is not empty and was not created by DocuForge (no ${OUTPUT_MARKER} marker).\n  Delete it yourself or choose a different --out.`,
          ExitCode.Usage,
        );
      }
      for (const entry of entries) {
        await fs.rm(path.join(outDir, entry), { recursive: true, force: true });
      }
    } else {
      foreignContent = entries.length > 0 && !marked;
    }
  } else {
    await fs.mkdir(outDir, { recursive: true });
  }

  await writeFileAtomic(path.join(outDir, OUTPUT_MARKER), "This directory is generated by DocuForge.\n");
  return { foreignContent };
}

/** Write a generated file; the destination is verified to stay inside `outDir`. */
export async function writeOutputFile(outDir: string, relPath: string, data: string | Uint8Array): Promise<void> {
  await writeFileAtomic(resolveInside(outDir, relPath), data);
}
