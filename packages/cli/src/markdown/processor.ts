export interface HeadingInfo {
  depth: number;
  id: string;
  text: string;
}

/** A link to a heading in another document, validated after all pages are rendered. */
export interface AnchorRef {
  from: string;
  route: string;
  anchor: string;
}

export interface ProcessorOptions {
  rawHtml: "sanitize" | "off";
  syntaxHighlighting: boolean;
  basePath: string;
  strictLinks: boolean;
}

export interface DocContext {
  relPath: string;
  index: LinkIndex;
  assets: AssetCollector;
  diags: Diagnostics;
  anchorRefs: AnchorRef[];
}

export interface RenderedMarkdown {
  html: string;
  headings: HeadingInfo[];
  /** Number of `<h1>` elements in the rendered content. */
  h1Count: number;
  /** Plain text of the first paragraph, trimmed to ~160 characters. */
  summary?: string;
  /** Plain visible text of the page content (used for search). */
  text: string;
}

interface DocData {
  ctx: DocContext;
  headings: HeadingInfo[];
  h1Count: number;
  summary?: string;
  text: string;
}

/** Reserved ids used by the page template; heading slugs must never collide with them. */
export const RESERVED_IDS = ["df-main", "df-toc", "df-copy-status", "df-nav"];

const ID_PREFIX = /^user-content-/;

/**
 * Sanitizing policy for Markdown content (documented in the README):
 * the GitHub-style allowlist from hast-util-sanitize, except that authored
 * `id`/`name` attributes are dropped (heading ids are generated by DocuForge;
 * only the footnote ids produced by remark-rehype survive) and `tel:` links are allowed.
 */
function buildSchema(): SanitizeSchema {
  const attributes: Record<string, NonNullable<SanitizeSchema["attributes"]>[string]> = {};
  for (const [tag, list] of Object.entries(defaultSchema.attributes ?? {})) {
    attributes[tag] = (list ?? []).filter((a) => {
      const name = Array.isArray(a) ? a[0] : a;
      return name !== "id" && name !== "name";
    });
  }
  attributes["*"] = [...(attributes["*"] ?? []), ["id", ID_PREFIX]];
  return {
    ...defaultSchema,
    // By default only <script> loses its contents; for any other disallowed element the children
    // survive as visible text (e.g. the CSS inside <style>). These elements carry no page content.
    strip: ["script", "style", "noscript", "template", "iframe", "object", "embed", "applet", "textarea", "title"],
    clobber: [],
    clobberPrefix: "",
    attributes,
    protocols: { ...defaultSchema.protocols, href: [...(defaultSchema.protocols?.["href"] ?? []), "tel"] },
  };
}

function textSummary(p: Element | undefined): string | undefined {
  if (!p) return undefined;
  const text = hastToString(p).replace(/\s+/g, " ").trim();
  if (text === "") return undefined;
  if (text.length <= 160) return text;
  const cut = text.slice(0, 160);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(" "), 100)).trimEnd()}…`;
}

function dataOf(file: VFile): DocData {
  return file.data["docuforge"] as DocData;
}

const CALLOUT_RE = /^\s*\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\][ \t]*\r?\n?/i;
const CALLOUT_TITLES: Record<string, string> = { note: "Note", tip: "Tip", important: "Important", warning: "Warning", caution: "Caution" };

/** GitHub-style callouts: `> [!NOTE]` turns a blockquote into a labelled note, tip, warning and so on. */
function rehypeCallouts() {
  return (tree: Root): void => {
    visit(tree, "element", (node, index, parent) => {
      if (node.tagName !== "blockquote" || parent === undefined || index === undefined) return;
      const firstP = node.children.find((c): c is Element => c.type === "element");
      const first = firstP?.children[0];
      if (!firstP || firstP.tagName !== "p" || !first || first.type !== "text") return;
      const m = CALLOUT_RE.exec(first.value);
      if (!m) return;
      const kind = (m[1] as string).toLowerCase();
      first.value = first.value.slice(m[0].length);
      if (first.value === "") firstP.children.shift();
      const lead = firstP.children[0];
      if (lead?.type === "element" && lead.tagName === "br") firstP.children.shift();
      const body = firstP.children.length === 0 ? node.children.filter((c) => c !== firstP) : node.children;
      parent.children[index] = {
        type: "element",
        tagName: "div",
        properties: { className: ["callout", `callout-${kind}`], role: "note" },
        children: [
          { type: "element", tagName: "p", properties: { className: ["callout-title"] }, children: [{ type: "text", value: CALLOUT_TITLES[kind] as string }] },
          ...body,
        ],
      };
    });
  };
}

/** An image alone in a paragraph with a title (`![alt](src "Caption")`) becomes a figure with a caption. */
function rehypeFigures() {
  return (tree: Root): void => {
    visit(tree, "element", (node, index, parent) => {
      if (node.tagName !== "p" || parent === undefined || index === undefined) return;
      const kids = node.children.filter((c) => !(c.type === "text" && c.value.trim() === ""));
      const img = kids[0];
      if (kids.length !== 1 || !img || img.type !== "element" || img.tagName !== "img") return;
      const title = img.properties?.["title"];
      if (typeof title !== "string" || title.trim() === "") return;
      delete img.properties["title"]; // shown as a caption instead of a tooltip
      parent.children[index] = {
        type: "element",
        tagName: "figure",
        properties: {},
        children: [img, { type: "element", tagName: "figcaption", properties: {}, children: [{ type: "text", value: title.trim() }] }],
      };
    });
  };
}

/** Capture plain text from the sanitized tree, before heading anchors and code chrome are added. */
function rehypeSearchText() {
  return (tree: Root, file: VFile): void => {
    dataOf(file).text = extractPlainText(tree);
  };
}

function rehypeHeadings() {
  return (tree: Root, file: VFile): void => {
    const data = dataOf(file);
    const slugger = new GithubSlugger();
    for (const id of RESERVED_IDS) slugger.slug(id);

    const firstP = tree.children.find((n): n is Element => n.type === "element" && n.tagName === "p");
    const summary = textSummary(firstP);
    if (summary !== undefined) data.summary = summary;

    visit(tree, "element", (node) => {
      const m = /^h([1-6])$/.exec(node.tagName);
      if (!m) return;
      const existing = node.properties?.["id"];
      if (typeof existing === "string" && ID_PREFIX.test(existing)) return; // footnote label
      const depth = Number(m[1]);
      const text = hastToString(node).replace(/\s+/g, " ").trim();
      const id = slugger.slug(text === "" ? "section" : text);
      node.properties = { ...node.properties, id };
      if (depth === 1) data.h1Count++;
      data.headings.push({ depth, id, text });
      node.children.push({
        type: "element",
        tagName: "a",
        properties: { className: ["anchor"], href: `#${id}`, ariaLabel: `Link to section: ${text}` },
        children: [{ type: "text", value: "#" }],
      });
    });
  };
}

function decodeFragment(hash: string): string {
  try {
    return decodeURIComponent(hash.slice(1));
  } catch {
    return hash.slice(1);
  }
}

function rehypeLinks(opts: ProcessorOptions) {
  const REPORT: Record<string, string> = {
    "missing-page": "link.broken-page",
    "outside-root": "link.outside-root",
    "draft-target": "link.draft-target",
    malformed: "link.malformed",
    "unsupported-scheme": "link.unsupported-scheme",
  };

  return async (tree: Root, file: VFile): Promise<void> => {
    const { ctx, headings } = dataOf(file);
    const ids = new Set(headings.map((h) => h.id));
    const report = (code: string, message: string): void =>
      ctx.diags.report(opts.strictLinks, code, message, ctx.relPath);

    const anchors: Element[] = [];
    const images: Element[] = [];
    visit(tree, "element", (node) => {
      if (node.tagName === "a" && typeof node.properties?.["href"] === "string") {
        if (!(node.properties["className"] as string[] | undefined)?.includes("anchor")) anchors.push(node);
      } else if (node.tagName === "img" && typeof node.properties?.["src"] === "string") images.push(node);
    });

    for (const node of anchors) {
      const href = node.properties["href"] as string;
      const res = resolveLink(href, ctx.relPath, ctx.index);
      switch (res.kind) {
        case "anchor": {
          const id = decodeFragment(res.hash);
          if (id !== "" && id !== "top" && !ids.has(id) && !ID_PREFIX.test(id)) {
            report("link.broken-anchor", `Anchor "${res.hash}" does not match any heading in this document.`);
          }
          break;
        }
        case "external":
          if (/^(https?:)?\/\//i.test(res.href)) {
            node.properties["target"] = "_blank";
            node.properties["rel"] = ["noopener", "noreferrer"];
          }
          break;
        case "page": {
          node.properties["href"] = pageUrl(opts.basePath, res.route, res.query, res.hash);
          if (res.hash !== "" && res.hash !== "#") {
            ctx.anchorRefs.push({ from: ctx.relPath, route: res.route, anchor: decodeFragment(res.hash) });
          }
          break;
        }
        case "file": {
          const out = await ctx.assets.reference(res.relPath, ctx.relPath);
          if (out !== undefined) node.properties["href"] = fileUrl(opts.basePath, out, res.query, res.hash);
          break;
        }
        case "error":
          report(REPORT[res.code] ?? "link.broken", `Broken link: ${res.message}.`);
          break;
      }
    }

    for (const node of images) {
      const src = node.properties["src"] as string;
      node.properties["loading"] = "lazy";
      node.properties["decoding"] = "async";
      const res = resolveLink(src, ctx.relPath, ctx.index);
      if (res.kind === "file") {
        const out = await ctx.assets.reference(res.relPath, ctx.relPath);
        if (out !== undefined) node.properties["src"] = fileUrl(opts.basePath, out, res.query, res.hash);
      } else if (res.kind === "error") {
        report(REPORT[res.code] ?? "link.broken", `Broken image: ${res.message}.`);
      } else if (res.kind === "page" || res.kind === "anchor") {
        report("link.malformed", `Image source "${src}" points to a page, not an image file.`);
      }
    }
  };
}

function rehypeCodeBlocks() {
  return (tree: Root): void => {
    visit(tree, "element", (node, index, parent) => {
      if (node.tagName !== "pre" || parent === undefined || index === undefined) return;
      const code = node.children.find((c): c is Element => c.type === "element" && c.tagName === "code");
      if (!code) return;
      const classes = (code.properties?.["className"] as string[] | undefined) ?? [];
      const lang = classes.find((c) => c.startsWith("language-"))?.slice("language-".length);
      const label = languageLabel(lang);

      node.properties = { ...node.properties, tabIndex: 0 };
      const header: Element = {
        type: "element",
        tagName: "div",
        properties: { className: ["code-header"] },
        children: [
          { type: "element", tagName: "span", properties: { className: ["code-lang"] }, children: [{ type: "text", value: label }] },
          {
            type: "element",
            tagName: "button",
            properties: { type: "button", className: ["copy-btn"], ariaLabel: `Copy ${label} code to clipboard` },
            children: [{ type: "text", value: "Copy" }],
          },
        ],
      };
      const wrapper: Element = {
        type: "element",
        tagName: "div",
        properties: { className: ["code-block"], ...(lang ? { dataLanguage: lang } : {}) },
        children: [header, node as ElementContent],
      };
      parent.children[index] = wrapper;
      return "skip";
    });
  };
}

/** Build a reusable Markdown -> safe HTML renderer. */
export function createRenderer(opts: ProcessorOptions) {
  const base = unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(remarkRehype, { allowDangerousHtml: opts.rawHtml === "sanitize" });
  const withRaw = opts.rawHtml === "sanitize" ? base.use(rehypeRaw) : base;
  const sanitized = withRaw.use(rehypeSanitize, buildSchema()).use(rehypeCallouts).use(rehypeFigures).use(rehypeSearchText).use(rehypeHeadings).use(rehypeLinks, opts);
  const highlighted = opts.syntaxHighlighting
    ? sanitized.use(rehypeHighlight, {
        languages: GRAMMARS,
        detect: false,
        ignoreMissing: true,
        plainText: ["text", "txt", "plain", "plaintext"],
      })
    : sanitized;
  const processor = highlighted.use(rehypeCodeBlocks).use(rehypeStringify).freeze();

  return async function render(markdown: string, ctx: DocContext): Promise<RenderedMarkdown> {
    const data: DocData = { ctx, headings: [], h1Count: 0, text: "" };
    const file = await processor.process({ value: markdown, data: { docuforge: data } });
    if (data.h1Count > 1) {
      ctx.diags.warn("markdown.multiple-h1", `Document has ${data.h1Count} top-level headings (h1); use one per page.`, ctx.relPath);
    }
    return {
      html: String(file),
      headings: data.headings,
      h1Count: data.h1Count,
      text: data.text,
      ...(data.summary !== undefined ? { summary: data.summary } : {}),
    };
  };
}
